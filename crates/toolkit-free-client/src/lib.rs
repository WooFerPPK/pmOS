//! Toolkit-free client library — Principle VII conformance
//! fixture.
//!
//! The ONLY thing this crate is allowed to depend on, among
//! the display system, is `display-proto` — the shared wire
//! format. It deliberately does NOT depend on the `toolkit`
//! crate; the whole point of this fixture is to prove that
//! any client that can read `display-proto` can drive the
//! display server without a toolkit in the loop.
//!
//! The code below is intentionally direct: [`FreeClient`]
//! contains the hand-written request encoders and [`FreeSession`]
//! contains the small event-driven state machine used by the
//! standalone WASI binary. A reader who has just read
//! `specs/001-browser-os-v1/contracts/display-protocol.md`
//! should be able to map every transition to a wire message.
//!
//! Principle VII says "Protocol over API for the display
//! server — Wayland-inspired wire protocol, toolkit is a
//! library wrapper". The `tests/conformance.rs` integration
//! test pairs [`FreeSession`] against a real
//! `display_server::Server` over in-memory byte buffers and walks
//! discovery, role creation, painting, input, and close cleanup. The
//! standalone binary drives the same state machine over the PMos
//! `/run/display` fd; the browser integration gate proves that path in a
//! separately isolated Worker.

